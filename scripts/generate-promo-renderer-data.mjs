import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { crosshairs } from '../src/data/crosshairs.js'
import { createTranslator, localizeCrosshair } from '../src/i18n/translations.js'

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outputFile = path.join(projectRoot, 'output/promo_assets/source/promo-crosshair-data.js')
const rendererFile = path.join(projectRoot, 'output/promo_assets/source/promo-renderer.html')
const mapFile = path.join(projectRoot, 'src/assets/maps/ascent.jpg')
const brandLogoFile = path.join(projectRoot, 'public/brand/aimcodes-logo-transparent-v2.png')

const locales = {
  'zh-cn': 'zh-CN',
  en: 'en',
  es: 'es',
  'pt-br': 'pt-BR',
}

const data = crosshairs.map((item) => ({
  id: item.id,
  code: item.code,
  color: item.color,
  previewScale: item.previewScale || 1.8,
  names: Object.fromEntries(
    Object.entries(locales).map(([promoLocale, siteLocale]) => {
      const localized = localizeCrosshair(item, siteLocale, createTranslator(siteLocale))
      return [promoLocale, { name: localized.name, shortName: localized.shortName }]
    }),
  ),
}))

const mapBase64 = (await readFile(mapFile)).toString('base64')
const brandLogoBase64 = (await readFile(brandLogoFile)).toString('base64')
const serializedData = JSON.stringify(data).replace(/</g, '\\u003c')
const source = `/* Generated by scripts/generate-promo-renderer-data.mjs. */
window.AIMCODES_PROMO_DATA = ${serializedData};
window.AIMCODES_PROMO_MAP = "data:image/jpeg;base64,${mapBase64}";
window.AIMCODES_PROMO_LOGO = "data:image/png;base64,${brandLogoBase64}";
`

await writeFile(outputFile, source)

const renderer = await readFile(rendererFile, 'utf8')
const embeddedData = `<!-- PROMO_DATA_START -->
    <script>
${source}    </script>
    <!-- PROMO_DATA_END -->`
const dataMarkerPattern = /<!-- PROMO_DATA_START -->[\s\S]*?<!-- PROMO_DATA_END -->/
if (!dataMarkerPattern.test(renderer)) throw new Error('Renderer data markers were not found')
const embeddedRenderer = renderer.replace(dataMarkerPattern, embeddedData)
await writeFile(rendererFile, embeddedRenderer)

console.log(`Generated ${data.length} crosshairs and embedded Ascent map + AimCodes logo in ${rendererFile}`)
